#!/usr/bin/env bash
set -euo pipefail

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

require_private_dir() {
  local path="$1"

  if [ -e "$path" ] || [ -L "$path" ]; then
    [ -d "$path" ] && [ ! -L "$path" ] || die "runtime path is not a directory: ${path}"
    [ -O "$path" ] || die "runtime path is not owned by the current user: ${path}"
  else
    install -d -m 0700 "$path"
  fi
  chmod 0700 "$path"
}

[ "$#" -ge 1 ] || die "missing command name"
tool="$1"
shift

# This can only launch the 4 sarus-suite tools
case "$tool" in
  sarusctl|podman|parallax|sarus-suite-check) ;;
  *) die "unsupported Sarus Suite command: ${tool}" ;;
esac

# Loading off environment metadata
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
SARUS_SUITE_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd -P)"
SARUS_SUITE_BIN="${SARUS_SUITE_ROOT}/libexec/sarus-suite/bin"
SARUS_SUITE_HOOK_BIN="${SARUS_SUITE_ROOT}/libexec/sarus-suite/oci/hooks"
SARUS_SUITE_CONFIG_HOME="${SARUS_SUITE_ROOT}/xdg/config"
SARUS_SUITE_STATE="${SARUS_SUITE_ROOT}/xdg/state/sarus-suite"
SARUS_SUITE_PODMAN_ROOT="${SARUS_SUITE_ROOT}/xdg/data/containers/storage"
INSTALL_ENV="${SARUS_SUITE_ROOT}/install/environment.sh"

# Prepares/installs the runtime env
[ -r "$INSTALL_ENV" ] || die "installed environment not found: ${INSTALL_ENV}"
# This file is generated by the user installer and owned by the same user.
# shellcheck source=/dev/null
source "$INSTALL_ENV"
: "${SARUS_SUITE_INSTALLED_PARALLAX_STORE:?missing installed Parallax store}"
SARUS_SUITE_PARALLAX_STORE="$SARUS_SUITE_INSTALLED_PARALLAX_STORE"
[ -z "${SARUS_SUITE_INSTALLED_PODMAN_GRAPHROOT:-}" ] || SARUS_SUITE_PODMAN_ROOT="$SARUS_SUITE_INSTALLED_PODMAN_GRAPHROOT"
SARUS_SUITE_PODMAN_RUNROOT="${SARUS_SUITE_INSTALLED_PODMAN_RUNROOT:-}"

[ -x "${SARUS_SUITE_BIN}/${tool}" ] || die "installed command not found: ${SARUS_SUITE_BIN}/${tool}"

# Scoping the XDG env install
if [ -n "${XDG_RUNTIME_DIR:-}" ] && [ -d "${XDG_RUNTIME_DIR}" ] && [ -w "${XDG_RUNTIME_DIR}" ]; then
  runtime_parent="${XDG_RUNTIME_DIR}"
else
  runtime_parent="/tmp/sarus-suite-${UID}"
  require_private_dir "$runtime_parent"
fi

SARUS_SUITE_RUNTIME="${runtime_parent}/sarus-suite"
require_private_dir "$SARUS_SUITE_RUNTIME"
require_private_dir "${SARUS_SUITE_RUNTIME}/tmp"

export SARUS_SUITE_ROOT
export SARUS_SUITE_BIN
export SARUS_SUITE_HOOK_BIN
export SARUS_SUITE_CONFIG_HOME
export SARUS_SUITE_STATE
export SARUS_SUITE_RUNTIME
export SARUS_SUITE_PARALLAX_STORE
export SARUS_SUITE_PODMAN_ROOT
export SARUS_SUITE_PODMAN_RUNROOT
export SARUS_SUITE_INSTALL_MODE=user

# Export sarus-suite bundle integration, note the PATH updates to the bundle!
export XDG_CONFIG_HOME="${SARUS_SUITE_ROOT}/xdg/config"
export XDG_DATA_HOME="${SARUS_SUITE_ROOT}/xdg/data"
export XDG_STATE_HOME="${SARUS_SUITE_ROOT}/xdg/state"
export XDG_CACHE_HOME="${SARUS_SUITE_ROOT}/xdg/cache"
export XDG_RUNTIME_DIR="${SARUS_SUITE_RUNTIME}"
export TMPDIR="${SARUS_SUITE_RUNTIME}/tmp"

export CONTAINERS_POLICY="${XDG_CONFIG_HOME}/containers/policy.json"
if [ -z "${CONTAINERS_REGISTRIES_CONF:-}" ] &&
   [ ! -e "${HOME}/.config/containers/registries.conf" ] &&
   [ ! -L "${HOME}/.config/containers/registries.conf" ] &&
   [ ! -e /etc/containers/registries.conf ] &&
   [ ! -L /etc/containers/registries.conf ]; then
  export CONTAINERS_REGISTRIES_CONF="${XDG_CONFIG_HOME}/containers/registries.conf"
fi
export PARALLAX_MP_CONFIG="${XDG_CONFIG_HOME}/parallax/parallax-mount.conf"
export SARUSCTL_CONFIG_DIR="${XDG_CONFIG_HOME}/sarus-suite"
export PATH="${SARUS_SUITE_BIN}:${PATH:-/usr/bin:/bin}"

# Self-replace with launch app, so no persistent wrapper needed all signals go to final app
exec "${SARUS_SUITE_BIN}/${tool}" "$@"
